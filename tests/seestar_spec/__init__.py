"""Validate Seestar JSON requests against the vendored seestar-spec catalog.

catalog.json is generated by scripts/sync_seestar_spec.py from
https://github.com/zmerlynn/seestar-spec (CC0). Re-run that script to pick
up a newer spec revision.

Validation is deliberately stricter than the firmware: the firmware ignores
undocumented keys, so sending one is almost always a bug (a misspelled
field that silently does nothing), and it is reported here.
"""

import json
from pathlib import Path

CATALOG = json.loads((Path(__file__).with_name("catalog.json")).read_text())
METHODS = CATALOG["methods"]

# Methods seestar_alp sends that are not in any analyzed firmware table.
# AGENTS.md requires keeping these compatibility fallbacks, so they are
# accepted by name and their params are not checked.
LEGACY_COMPAT_METHODS = frozenset(
    {"get_stack_setting", "set_stack_setting", "set_stack_settings"}
)


class _Unknown:
    """A value computed at runtime; static source scans cannot check it."""

    def __repr__(self):
        return "UNKNOWN"


UNKNOWN = _Unknown()


def _strip_verify_marker(params):
    """Undo seestar_device.transform_message_for_verify's auth marker.

    seestar-spec does not describe it, but it is a deliberate compatibility
    path (issues #748/#758): a trailing "verify" on list params, ["verify"]
    for params-less requests, and "verify": true in dict params (fw < 2706).
    Returns (has_params, params).
    """
    if isinstance(params, list) and params and params[-1] == "verify":
        params = params[:-1]
        if not params:
            return False, None
        # A scalar is sent as [scalar, "verify"]; the remaining one-element
        # list is checked as-is, since the methods that take a bare scalar
        # also accept it as the first array element.
        return True, params
    if isinstance(params, dict) and params.get("verify") is True:
        params = {k: v for k, v in params.items() if k != "verify"}
    return True, params


def _json_type(value):
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if isinstance(value, str):
        return "string"
    if isinstance(value, (list, tuple)):
        return "array"
    if isinstance(value, dict):
        return "object"
    return type(value).__name__


def _type_ok(value, types):
    actual = _json_type(value)
    if actual in types:
        return True
    if actual == "integer" and "number" in types:
        return True
    return actual == "number" and "integer" in types and float(value).is_integer()


def _check(value, shape, path):
    if value is UNKNOWN:
        return []
    if "anyOf" in shape:
        best = None
        for alt in shape["anyOf"]:
            merged = {k: v for k, v in shape.items() if k != "anyOf"} | alt
            problems = _check(value, merged, path)
            if not problems:
                return []
            # Report the alternative of the value's own type: "undocumented
            # key" says more than "object not allowed (expected integer)".
            rank = (not _type_ok(value, merged.get("types") or []), len(problems))
            if best is None or rank < best[0]:
                best = (rank, problems)
        return best[1]

    types = shape.get("types")
    if types and not _type_ok(value, types):
        return [f"{path}: {_json_type(value)} not allowed (expected {'|'.join(types)})"]

    problems = []
    if "enum" in shape:
        allowed = shape["enum"]
        if shape.get("case_insensitive") and isinstance(value, str):
            ok = value.lower() in [str(a).lower() for a in allowed]
        else:
            ok = value in allowed
        if not ok:
            problems.append(f"{path}: {value!r} not one of {allowed}")

    if isinstance(value, (int, float)) and not isinstance(value, bool):
        if "minimum" in shape and value < shape["minimum"]:
            problems.append(f"{path}: {value} below minimum {shape['minimum']}")
        if "maximum" in shape and value > shape["maximum"]:
            problems.append(f"{path}: {value} above maximum {shape['maximum']}")

    if isinstance(value, dict):
        props = shape.get("properties", {})
        for key in shape.get("required", []):
            if key not in value:
                problems.append(f"{path}.{key}: required key missing")
        for key, sub in value.items():
            if key in props:
                problems += _check(sub, props[key], f"{path}.{key}")
            elif not shape.get("open"):
                problems.append(f"{path}.{key}: undocumented key")

    if isinstance(value, (list, tuple)):
        prefix = shape.get("prefixItems", [])
        for i, item in enumerate(value):
            sub = prefix[i] if i < len(prefix) else shape.get("items")
            if sub:
                problems += _check(item, sub, f"{path}[{i}]")
    return problems


def validate_request(request):
    """Return a list of human-readable problems; empty when it conforms."""
    method = request.get("method")
    if method in LEGACY_COMPAT_METHODS:
        return []
    spec = METHODS.get(method)
    if spec is None:
        return [f"method {method!r} is not in seestar-spec"]
    has_params = "params" in request
    if has_params:
        has_params, params = _strip_verify_marker(request["params"])
    if not has_params:
        if spec["params_required"]:
            return [f"{method}: params is required"]
        return []
    if spec["params"] is None:
        return [f"{method}: method takes no params"]
    # Paths read like the field names on the spec cards ("stack.bogus").
    problems = _check(params, spec["params"], "params")
    return [f"{method}: {p.removeprefix('params.')}" for p in problems]
